/// 8-bit RGB conversion matches ColorFilter.matrix (including clamping).
List<int> storyFilteredRgb(List<double> matrix, num r, num g, num b) => [
  for (final offset in const [0, 5, 10])
    (matrix[offset] * r +
            matrix[offset + 1] * g +
            matrix[offset + 2] * b +
            matrix[offset + 4])
        .round()
        .clamp(0, 255),
];
