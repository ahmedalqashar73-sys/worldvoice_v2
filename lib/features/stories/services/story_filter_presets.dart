/// Shared by live preview, photo export, and published video playback.
enum StoryPhotoFilter {
  original,
  vivid,
  warm,
  cool,
  mono,
  vintage,
  rose,
  cinema,
}

StoryPhotoFilter storyFilterFromName(String name) =>
    StoryPhotoFilter.values.firstWhere(
      (filter) => filter.name == name,
      orElse: () => StoryPhotoFilter.original,
    );

