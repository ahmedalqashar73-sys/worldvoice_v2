class ProfileLanguage {
  const ProfileLanguage(this.code, this.englishName, [this.nativeName]);
  final String code;
  final String englishName;
  final String? nativeName;

  String get displayName =>
      nativeName == null || nativeName == englishName ? englishName : '${nativeName!} — $englishName';
}

