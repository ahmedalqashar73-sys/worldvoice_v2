/// Page plan for original WorldVoice novels; keeps every paragraph intact.
/// Pages remain vertically scrollable on compact screens to avoid clipping.
class NovelBookPart {
  const NovelBookPart.paragraph(this.text) : imageAsset = null;
  const NovelBookPart.image(this.imageAsset) : text = null;

  final String? text;
  final String? imageAsset;
}

class NovelBookPage {
  const NovelBookPage({
    required this.kind,
    required this.heading,
    this.chapterNumber,
    this.parts = const <NovelBookPart>[],
    this.continued = false,
  });

  /// cover, introduction, characters, contents, chapter, ending
  final String kind;
  final String heading;
  final int? chapterNumber;
  final List<NovelBookPart> parts;
  final bool continued;
}

List<NovelBookPage> buildNovelBookPages(Map<String, dynamic> novel) {
  final rawChapters = novel['chapters'];
  if (rawChapters is! List || rawChapters.length < 5) {
    throw const FormatException('Novel must have five or more chapters.');
  }
  final result = <NovelBookPage>[
    NovelBookPage(kind: 'cover', heading: novel['title'] as String),
    NovelBookPage(kind: 'title', heading: novel['title'] as String),
    const NovelBookPage(kind: 'contents', heading: 'Contents'),
    NovelBookPage(
      kind: 'introduction',
      heading: 'Story Introduction',
      parts: [NovelBookPart.paragraph(novel['synopsis'] as String)],
    ),
  ];
  final characters = novel['characters'];
  if (characters is List && characters.isNotEmpty) {
    final items = <NovelBookPart>[];
    for (final value in characters) {
      final character = value as Map<String, dynamic>;
      items.add(NovelBookPart.paragraph(
        character['name'].toString() + ' — ' +
            character['description'].toString(),
      ));
    }
    // Keep the character sheet readable on narrow screens.
    for (var i = 0; i < items.length; i += 3) {
      final end = i + 3 > items.length ? items.length : i + 3;
      result.add(NovelBookPage(
        kind: 'characters',
        heading: 'Characters',
        continued: i > 0,
        parts: items.sublist(i, end),
      ));
    }
  }
  for (var chapterIndex = 0; chapterIndex < rawChapters.length;
      chapterIndex++) {
    final chapter = rawChapters[chapterIndex] as Map<String, dynamic>;
    final chapterNumber = chapterIndex + 1;
    final heading = chapter['title'] as String;
    final paragraphs = chapter['paragraphs'] as List;
    if (paragraphs.length < 5) {
      throw FormatException(
        'Chapter ' + chapterNumber.toString() + ' has too few paragraphs.');
    }
    var parts = <NovelBookPart>[];
    var used = 0;
    var continuation = false;

    void flush() {
      if (parts.isEmpty) return;
      result.add(NovelBookPage(
        kind: 'chapter',
        heading: heading,
        chapterNumber: chapterNumber,
        continued: continuation,
        parts: List<NovelBookPart>.unmodifiable(parts),
      ));
      parts = <NovelBookPart>[];
      used = 0;
      continuation = true;
    }

    void addPart(NovelBookPart part, int cost) {
      final capacity = continuation ? 160 : 125;
      if (parts.isNotEmpty && used + cost > capacity) flush();
      parts.add(part);
      used += cost;
    }

    for (var paragraphIndex = 0;
        paragraphIndex < paragraphs.length; paragraphIndex++) {
      // Existing illustrations only; no artwork is generated by the reader.
      if (paragraphIndex == 3 &&
          chapter['image'] is String &&
          (chapter['image'] as String).isNotEmpty) {
        addPart(NovelBookPart.image(chapter['image'] as String), 90);
      }
      final paragraph = paragraphs[paragraphIndex] as String;
      final wordCount = paragraph.trim().split(RegExp(r'\s+')).length;
      addPart(NovelBookPart.paragraph(paragraph), wordCount);
      if (paragraphIndex == 9 &&
          chapter['extra_image'] is String &&
          (chapter['extra_image'] as String).isNotEmpty) {
        addPart(NovelBookPart.image(chapter['extra_image'] as String), 90);
      }
    }
    flush();
  }
  result.add(const NovelBookPage(kind: 'ending', heading: 'The End'));
  return List<NovelBookPage>.unmodifiable(result);
}
