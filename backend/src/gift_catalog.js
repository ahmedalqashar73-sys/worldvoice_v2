export function approvedWorldVoiceGift(giftId, priceCoins) {
  const item = worldVoiceGiftCatalog.get(String(giftId || ""));
  return item && Number(priceCoins) === item.priceCoins ? item : null;
}

export function worldVoiceGiftStoreDocument(giftId) {
  const item = worldVoiceGiftCatalog.get(giftId);
  if (!item) return null;
  return {
    type: "gift",
    legacyId: giftId,
    name: item.name,
    nameAr: item.nameAr,
    priceCoins: item.priceCoins,
    requiredGiftLevel: 0,
    durationDays: null,
    animationUrl: null,
    previewUrl: "",
    active: true,
    tier: item.tier,
    sourceCollection: "worldvoice_gifts_v1",
    builtInVisual: true,
  };
}


export async function syncWorldVoiceGiftStore(db) {
  const approvedIds = new Set(
    [...worldVoiceGiftCatalog.keys()].map((giftId) => `gift__${giftId}`),
  );
  const existing = await db.collection("store_items")
    .where("type", "==", "gift")
    .get();

  const batch = db.batch();
  let retired = 0;
  for (const doc of existing.docs) {
    if (approvedIds.has(doc.id)) continue;
    batch.set(doc.ref, {
      active: false,
      retiredFromCatalog: true,
      retiredBy: "worldvoice_gifts_v1",
    }, {merge: true});
    retired += 1;
  }

  for (const giftId of worldVoiceGiftCatalog.keys()) {
    const data = worldVoiceGiftStoreDocument(giftId);
    batch.set(db.doc(`store_items/gift__${giftId}`), {
      ...data,
      retiredFromCatalog: false,
      needsCatalogReview: false,
    }, {merge: true});
  }

  await batch.commit();
  return {approved: worldVoiceGiftCatalog.size, retired};
}
